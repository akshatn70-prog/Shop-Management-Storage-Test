import fs from "node:fs";

const manifestPath = "android/app/src/main/AndroidManifest.xml";
if (!fs.existsSync(manifestPath)) throw new Error("AndroidManifest.xml was not generated by Capacitor.");

let xml = fs.readFileSync(manifestPath, "utf8");
if (xml.includes('android:scheme="shopmanagement"') && xml.includes('android:host="auth-callback"')) process.exit(0);

const activityMatch = xml.match(/<activity\b[^>]*android:name="[^"]*MainActivity"[^>]*>/s);
if (!activityMatch || activityMatch.index === undefined) {
  throw new Error("MainActivity activity was not found in AndroidManifest.xml.");
}

const activityStart = activityMatch.index;
const activityEnd = xml.indexOf("</activity>", activityStart);
if (activityEnd < 0) throw new Error("MainActivity activity closing tag was not found.");

const intentFilter = [
  "            <intent-filter>",
  "                <action android:name=\"android.intent.action.VIEW\" />",
  "                <category android:name=\"android.intent.category.DEFAULT\" />",
  "                <category android:name=\"android.intent.category.BROWSABLE\" />",
  "                <data android:scheme=\"shopmanagement\" android:host=\"auth-callback\" />",
  "            </intent-filter>"
].join("\n");

xml = xml.slice(0, activityEnd) + intentFilter + "\n        " + xml.slice(activityEnd);
fs.writeFileSync(manifestPath, xml);
console.log("Configured shopmanagement://auth-callback deep link.");
